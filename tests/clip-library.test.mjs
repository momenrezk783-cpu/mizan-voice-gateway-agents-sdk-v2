import assert from 'node:assert/strict';
import {importTs} from './helpers/runtime.mjs';
const {CLIP_TEXTS, matchClipSlug, clipPool, pickClipVariant} = await importTs('src/lib/clips/registry.ts');
assert.equal(CLIP_TEXTS.length, 71);
assert.equal(matchClipSlug('ثانية واحدة، خليني أشوف.'), 's01');
assert.equal(matchClipSlug('ثانية واحده خليني اشوف'), 's01');
assert.equal(matchClipSlug('صباح الخير. ميزان، مؤسسة في الإسكندرية، بنعمل مساعدين صوتيين وبرمجيات وأتمتة.'), 'q01');
assert.equal(matchClipSlug('خلاص، كده تمام.'), 'c05');
assert.equal(matchClipSlug('كلام حر مش موجود في المكتبة'), null);
assert.deepEqual(clipPool('q01'), ['q01','q01_t2','q01_t3']);
assert.deepEqual(clipPool('s15'), ['s15','c05','c05_t2','c05_t3']);
assert.deepEqual(clipPool('q09'), ['q09']);
const played = new Set();
const picks = [pickClipVariant('q01','call-1',played), pickClipVariant('q01','call-1',played), pickClipVariant('q01','call-1',played)];
picks.forEach(p => played.add(p));
assert.equal(new Set(picks).size, 3);
assert.equal(pickClipVariant('q01','call-1',played), null);
assert.equal(pickClipVariant('q01','call-x',new Set()), pickClipVariant('q01','call-x',new Set()));
const starts = new Set(['s1','s2','s3','s4','s5','s6'].map(id => pickClipVariant('q01', id, new Set())));
assert.ok(starts.size >= 2, 'rotation across calls');
console.log('PASS clip library: matching, shared pools, in-call no-repeat, cross-call rotation');
