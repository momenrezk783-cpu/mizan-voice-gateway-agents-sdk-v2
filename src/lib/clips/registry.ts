const TAKES: Record<string, string[]> = {
  q01:["q01_t2","q01_t3"], s01:["s01_t2","s01_t3"], s17:["s17_t2","s17_t3"],
  c01:["c01_t2","c01_t3"], c02:["c02_t2","c02_t3"], c03:["c03_t2","c03_t3"],
  c04:["c04_t2","c04_t3"], c05:["c05_t2","c05_t3"]
};

export type ClipEntry = readonly [string, string];
export const CLIP_TEXTS: readonly ClipEntry[] = [
  ...Object.entries(BASE).map(([slug, text]) => [slug, text] as const),
  ...Object.entries(TAKES).flatMap(([slug, takes]) => takes.map((take) => [take, BASE[slug]] as const))
];

export function clipPool(slug: string): string[] {
  if (slug === "s15" || slug === "c05") return ["s15", "c05", "c05_t2", "c05_t3"];
  const takes = TAKES[slug];
  return takes ? [slug, ...takes] : [slug];
}

const GREETING_LEAD = /^(?:صباح\s+الخير|مساء\s+الخير|أهلا\s+وسهلا|أهلا\s+بيك|أهلا|اهلا|السلام\s+عليكم|hello|hi)[.!،,؟?\s]*/iu;

const normalize = (t: string): string =>
  t.replace(/[\u064B-\u065F\u0670\u0640]/gu, "")
    .replace(/[أإآ]/gu, "ا")
    .replace(/ة/gu, "ه")
    .replace(/ى/gu, "ي")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim();

const TEXT_TO_SLUG = new Map<string, string>();
for (const [slug, text] of CLIP_TEXTS) TEXT_TO_SLUG.set(normalize(text), slug);

export function matchClipSlug(text: string): string | null {
  const value = String(text ?? "").trim();
  if (!value) return null;
  const direct = TEXT_TO_SLUG.get(normalize(value));
  if (direct) return direct;
  const stripped = value.replace(GREETING_LEAD, "");
  return stripped && stripped !== value ? TEXT_TO_SLUG.get(normalize(stripped)) ?? null : null;
}

function hash32(value: string): number {
  let h = 5381;
  for (let i = 0; i < value.length; i++) h = ((h * 33) ^ value.charCodeAt(i)) >>> 0;
  return h >>> 0;
}

/** بديل غير مكرر داخل نفس المكالمة؛ null لو البدائل خلصت (نرجع للتوليد الحي). */
export function pickClipVariant(slug: string, sessionId: string, played: ReadonlySet<string>): string | null {
  const pool = clipPool(slug);
  const start = hash32(sessionId + "|" + slug) % pool.length;
  for (let i = 0; i < pool.length; i++) {
    const variant = pool[(start + i) % pool.length];
    if (!played.has(variant)) return variant;
  }
  return null;
}

